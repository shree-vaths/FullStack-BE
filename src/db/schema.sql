-- Postgres schema for the users / transactions app.
-- Same tables as supabase/supabase_setup.sql, written to be re-runnable
-- (IF NOT EXISTS). The server does not run this on startup; it is used by the
-- tests and to set up a fresh, empty database.

CREATE TABLE IF NOT EXISTS users (
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              TEXT   NOT NULL,
  registration_date DATE   NOT NULL,
  country           TEXT   NOT NULL,
  service_level     TEXT   NOT NULL
                    CHECK (service_level IN ('basic', 'premium', 'elite'))
);

CREATE TABLE IF NOT EXISTS transactions (
  id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT  NOT NULL REFERENCES users (id) ON DELETE CASCADE,
  -- No services table was specified, so service_id is a plain identifier for now.
  service_id    INTEGER NOT NULL,
  -- Money as integer cents avoids floating-point rounding (e.g. 0.1 + 0.2).
  price_cents   INTEGER NOT NULL CHECK (price_cents >= 0),
  service_date  DATE    NOT NULL
);

-- "Transactions for a user, newest first" is the main query.
CREATE INDEX IF NOT EXISTS idx_transactions_user_id_service_date
  ON transactions (user_id, service_date DESC, id DESC);

-- Sort columns of the users list.
CREATE INDEX IF NOT EXISTS idx_users_name ON users (lower(name), id);
CREATE INDEX IF NOT EXISTS idx_users_registration_date ON users (registration_date, id);

-- Supabase exposes "public" tables through its REST API to anyone holding the
-- anon key. RLS with no policies blocks that; the server connects as the
-- postgres role, which RLS doesn't restrict.
ALTER TABLE users        ENABLE ROW LEVEL SECURITY;
ALTER TABLE transactions ENABLE ROW LEVEL SECURITY;
