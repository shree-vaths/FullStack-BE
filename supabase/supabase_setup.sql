-- -----------------------------------------------------------------------------
-- 1. Tables (Postgres equivalent of server/src/db/schema.sql)
-- -----------------------------------------------------------------------------

CREATE TABLE public.users (
  -- BY DEFAULT (not ALWAYS) so the seed can insert the original ids;
  -- the sequence is moved past them in step 4.
  id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name              TEXT   NOT NULL,
  registration_date DATE   NOT NULL,
  country           TEXT   NOT NULL,
  service_level     TEXT   NOT NULL
                    CHECK (service_level IN ('basic', 'premium', 'elite'))
);

CREATE TABLE public.transactions (
  id            BIGINT  GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id       BIGINT  NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
  service_id    INTEGER NOT NULL,
  -- Money as integer cents (12345 = $123.45) to avoid rounding errors.
  price_cents   INTEGER NOT NULL CHECK (price_cents >= 0),
  service_date  DATE    NOT NULL
);

-- Main query: one user's transactions, sorted by date (default) and paginated.
CREATE INDEX idx_transactions_user_id_service_date
  ON public.transactions (user_id, service_date DESC, id DESC);

-- Sort columns of the users list.
CREATE INDEX idx_users_name ON public.users (lower(name), id);
CREATE INDEX idx_users_registration_date ON public.users (registration_date, id);

-- -----------------------------------------------------------------------------
-- 2. Security: enable Row Level Security with NO policies.
--    Supabase exposes tables in "public" through its auto-generated REST API to
--    anyone holding the project's public anon key. With RLS on and no policies,
--    that API returns nothing. Our server connects directly with the database
--    connection string (postgres role), which is not affected by RLS.
-- -----------------------------------------------------------------------------

ALTER TABLE public.users        ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.transactions ENABLE ROW LEVEL SECURITY;

